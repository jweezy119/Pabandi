import {
  ComputeBudgetProgram,
  Connection,
  Keypair,
  PublicKey,
  VersionedTransaction,
} from '@solana/web3.js';
import {
  TOKEN_PROGRAM_ID,
  TOKEN_2022_PROGRAM_ID,
  getAssociatedTokenAddressSync,
} from '@solana/spl-token';
import * as anchor from '@coral-xyz/anchor';
import { prisma } from '../utils/database';
import { logger } from '../utils/logger';
import { webacyRiskService } from './webacyRisk.service';
import IDL from '../utils/pabandi_escrow.json';

const SOLANA_CLUSTER = (process.env.SOLANA_CLUSTER || 'devnet').toLowerCase();
const IS_MAINNET = SOLANA_CLUSTER === 'mainnet-beta' || SOLANA_CLUSTER === 'mainnet';

const PROGRAM_ID = new PublicKey(
  process.env.SOLANA_ESCROW_PROGRAM_ID || (IDL as any).address || 'EUSLC8q2b2SezvMQFhvU98EFrWkEasTdvrjqdJgYn2qc'
);
const TREASURY_WALLET = new PublicKey(
  process.env.PABANDI_TREASURY_WALLET ||
    process.env.SOLANA_TREASURY_WALLET ||
    'F5W934e6qJb8z2GZJj3kGjUfN6xLqK4W7CpHbBvRmN3D'
);
const CASH_MINT =
  process.env.SOLANA_CASH_MINT || 'CASHx9KJUStyftLFWGvEVf59SGeG9sh5FfcnZMVPCASH';

// Load Oracle Keypair securely from env (Tier 1 Attestation & Settlement Oracle)
const ORACLE_SECRET_KEY = process.env.SOLANA_ORACLE_SECRET_KEY;
let oracleKeypair: Keypair | null = null;
if (ORACLE_SECRET_KEY) {
  oracleKeypair = Keypair.fromSecretKey(new Uint8Array(JSON.parse(ORACLE_SECRET_KEY)));
}

if (!oracleKeypair) {
  logger.warn(
    '[SolanaEscrow] SOLANA_ORACLE_SECRET_KEY is not configured. ' +
      'Oracle signing operations (initialize_escrow, release_escrow, resolve_dispute) ' +
      'will throw at runtime. Set the env var to enable on-chain escrow flows.'
  );
}

const connection = new Connection(
  process.env.SOLANA_RPC_URL ||
    (IS_MAINNET ? 'https://api.mainnet-beta.solana.com' : 'https://api.devnet.solana.com'),
  'confirmed'
);

const provider = new anchor.AnchorProvider(
  connection,
  new anchor.Wallet(oracleKeypair || Keypair.generate()),
  { commitment: 'confirmed' }
);
const program = new anchor.Program(IDL as anchor.Idl, provider);

function deriveProtocolConfigPDA(): PublicKey {
  return PublicKey.findProgramAddressSync([Buffer.from('protocol_config')], PROGRAM_ID)[0];
}

function deriveEscrowPDAs(reservationId: string, customerWallet: PublicKey) {
  const [escrowStatePDA] = PublicKey.findProgramAddressSync(
    [Buffer.from('escrow_state'), Buffer.from(reservationId), customerWallet.toBuffer()],
    PROGRAM_ID
  );
  const [vaultTokenPDA] = PublicKey.findProgramAddressSync(
    [Buffer.from('escrow_vault'), Buffer.from(reservationId), customerWallet.toBuffer()],
    PROGRAM_ID
  );
  return { escrowStatePDA, vaultTokenPDA };
}

function resolveTokenProgramId(mintAddressStr: string): PublicKey {
  if (mintAddressStr === CASH_MINT) {
    return TOKEN_2022_PROGRAM_ID;
  }
  return TOKEN_PROGRAM_ID;
}

export const solanaEscrowService = {
  getProgramInfo() {
    return {
      programId: PROGRAM_ID.toBase58(),
      protocolConfigPda: deriveProtocolConfigPDA().toBase58(),
      treasuryWallet: TREASURY_WALLET.toBase58(),
      cluster: SOLANA_CLUSTER,
    };
  },

  /**
   * Partially signs the `initialize_escrow` transaction generated by the frontend.
   * Rejects any transaction containing unexpected instructions outside ComputeBudget + `initialize_escrow`.
   */
  async signInitializeEscrowTx(
    serializedTxBase64: string,
    customerWallet: string
  ): Promise<string> {
    if (!oracleKeypair) {
      throw new Error('Oracle Keypair not configured on backend.');
    }

    const txBuffer = Buffer.from(serializedTxBase64, 'base64');
    let transaction: VersionedTransaction;
    try {
      transaction = VersionedTransaction.deserialize(txBuffer);
    } catch {
      throw new Error('Invalid serialized transaction');
    }

    const message = transaction.message;
    const programIdIndex = message.staticAccountKeys.findIndex((k) => k.equals(PROGRAM_ID));
    const computeBudgetIndex = message.staticAccountKeys.findIndex((k) =>
      k.equals(ComputeBudgetProgram.programId)
    );

    if (programIdIndex === -1) {
      throw new Error('Transaction does not interact with the expected Pabandi Escrow Program ID.');
    }

    // initialize_escrow discriminator from IDL: [243, 160, 77, 153, 11, 92, 48, 209]
    const INITIALIZE_ESCROW_DISCRIMINATOR = new Uint8Array([
      243, 160, 77, 153, 11, 92, 48, 209,
    ]);

    let validInitializeInstructionCount = 0;

    for (const ix of message.compiledInstructions) {
      // Allow optional ComputeBudget instructions only alongside our exact initialize_escrow ix
      if (computeBudgetIndex !== -1 && ix.programIdIndex === computeBudgetIndex) {
        continue;
      }
      if (ix.programIdIndex !== programIdIndex) {
        throw new Error('Refusing to co-sign transaction containing unauthorized program instructions.');
      }
      const data = ix.data;
      if (data.length < INITIALIZE_ESCROW_DISCRIMINATOR.length) {
        throw new Error('Invalid instruction data length for Pabandi Escrow program.');
      }
      const matches = INITIALIZE_ESCROW_DISCRIMINATOR.every((b, idx) => data[idx] === b);
      if (!matches) {
        throw new Error('Refusing to co-sign non-initialize_escrow instruction.');
      }
      validInitializeInstructionCount++;
    }

    if (validInitializeInstructionCount !== 1) {
      throw new Error('Transaction must contain exactly one initialize_escrow instruction.');
    }

    // Fetch real-time trust score record for this customer
    const user = await prisma.user.findUnique({
      where: { walletAddress: customerWallet },
    });
    if (!user) {
      throw new Error(`Oracle user not registered for wallet: ${customerWallet}`);
    }

    // Screen customer wallet via Webacy Risk Intelligence before co-signing escrow.
    // Hard-blocks sanctioned or critical-risk wallets; fails open with warning on free-tier 429/timeout.
    await webacyRiskService.assertSolanaWalletSafeForEscrow(customerWallet);

    // Co-sign as the Tier 1 Attestation Oracle
    transaction.sign([oracleKeypair]);
    return Buffer.from(transaction.serialize()).toString('base64');
  },

  /**
   * Oracle-Triggered Release (e.g. from check-in confirmation or completed milestone).
   * Supports both SPL Token (USDC) and Token-2022 (Phantom CASH).
   */
  async triggerReleaseEscrow(
    reservationId: string,
    customerWalletStr: string,
    businessWalletStr: string,
    mintAddressStr: string
  ): Promise<string> {
    if (!oracleKeypair) {
      throw new Error('Oracle Keypair not configured on backend.');
    }

    const customerWallet = new PublicKey(customerWalletStr);
    const businessWallet = new PublicKey(businessWalletStr);
    const mintAddress = new PublicKey(mintAddressStr);
    const tokenProgramId = resolveTokenProgramId(mintAddressStr);

    const protocolConfigPDA = deriveProtocolConfigPDA();
    const { escrowStatePDA, vaultTokenPDA } = deriveEscrowPDAs(reservationId, customerWallet);

    const businessTokenAccount = getAssociatedTokenAddressSync(
      mintAddress,
      businessWallet,
      false,
      tokenProgramId
    );
    const treasuryTokenAccount = getAssociatedTokenAddressSync(
      mintAddress,
      TREASURY_WALLET,
      false,
      tokenProgramId
    );

    logger.info(`[Escrow Oracle] Triggering Release for ${reservationId} (${SOLANA_CLUSTER})...`);

    try {
      const tx = await (program.methods as any)
        .releaseEscrow()
        .accounts({
          oracleTrigger: oracleKeypair.publicKey,
          protocolConfig: protocolConfigPDA,
          customer: customerWallet,
          mint: mintAddress,
          escrowState: escrowStatePDA,
          vaultTokenAccount: vaultTokenPDA,
          businessTokenAccount,
          treasuryTokenAccount,
          tokenProgram: tokenProgramId,
        })
        .signers([oracleKeypair])
        .rpc();

      logger.info(`[Escrow Oracle] Released funds. Tx: ${tx}`);
      return tx;
    } catch (err: any) {
      logger.error(`[Escrow Oracle] Release failed: ${err.message}`);
      throw new Error(`Release failed: ${err.message}`);
    }
  },

  /**
   * Oracle-Triggered Sulha Dispute Resolution (splits locked deposit by businessBps 0..=10000).
   */
  async triggerResolveDispute(
    reservationId: string,
    customerWalletStr: string,
    businessWalletStr: string,
    mintAddressStr: string,
    businessBps: number
  ): Promise<string> {
    if (!oracleKeypair) {
      throw new Error('Oracle Keypair not configured on backend.');
    }
    if (!Number.isInteger(businessBps) || businessBps < 0 || businessBps > 10000) {
      throw new Error('businessBps must be an integer between 0 and 10000');
    }

    const customerWallet = new PublicKey(customerWalletStr);
    const businessWallet = new PublicKey(businessWalletStr);
    const mintAddress = new PublicKey(mintAddressStr);
    const tokenProgramId = resolveTokenProgramId(mintAddressStr);

    const protocolConfigPDA = deriveProtocolConfigPDA();
    const { escrowStatePDA, vaultTokenPDA } = deriveEscrowPDAs(reservationId, customerWallet);

    const businessTokenAccount = getAssociatedTokenAddressSync(
      mintAddress,
      businessWallet,
      false,
      tokenProgramId
    );
    const customerTokenAccount = getAssociatedTokenAddressSync(
      mintAddress,
      customerWallet,
      false,
      tokenProgramId
    );
    const treasuryTokenAccount = getAssociatedTokenAddressSync(
      mintAddress,
      TREASURY_WALLET,
      false,
      tokenProgramId
    );

    const tx = await (program.methods as any)
      .resolveDispute(businessBps)
      .accounts({
        oracleTrigger: oracleKeypair.publicKey,
        protocolConfig: protocolConfigPDA,
        customer: customerWallet,
        mint: mintAddress,
        escrowState: escrowStatePDA,
        vaultTokenAccount: vaultTokenPDA,
        businessTokenAccount,
        customerTokenAccount,
        treasuryTokenAccount,
        tokenProgram: tokenProgramId,
      })
      .signers([oracleKeypair])
      .rpc();

    logger.info(`[Escrow Oracle] Resolved dispute (${businessBps} bps). Tx: ${tx}`);
    return tx;
  },

  /**
   * Builds an unsigned refund transaction for the customer to sign and submit after deadline.
   */
  async triggerRefundEscrow(
    reservationId: string,
    customerWalletStr: string,
    mintAddressStr: string
  ): Promise<string> {
    const customerWallet = new PublicKey(customerWalletStr);
    const mintAddress = new PublicKey(mintAddressStr);
    const tokenProgramId = resolveTokenProgramId(mintAddressStr);

    const { escrowStatePDA, vaultTokenPDA } = deriveEscrowPDAs(reservationId, customerWallet);
    const customerTokenAccount = getAssociatedTokenAddressSync(
      mintAddress,
      customerWallet,
      false,
      tokenProgramId
    );

    logger.info(`[Escrow Oracle] Building refund tx for ${reservationId} (customer must sign)...`);

    try {
      const tx = await (program.methods as any)
        .refundEscrow()
        .accounts({
          customer: customerWallet,
          mint: mintAddress,
          escrowState: escrowStatePDA,
          vaultTokenAccount: vaultTokenPDA,
          customerTokenAccount,
          tokenProgram: tokenProgramId,
        })
        .transaction();

      const { blockhash } = await connection.getLatestBlockhash('confirmed');
      tx.feePayer = customerWallet;
      tx.recentBlockhash = blockhash;

      const serialized = Buffer.from(
        tx.serialize({ requireAllSignatures: false, verifySignatures: false })
      ).toString('base64');

      logger.info(`[Escrow Oracle] Refund tx prepared for ${reservationId}.`);
      return serialized;
    } catch (err: any) {
      logger.error(`[Escrow Oracle] Refund tx build failed for ${reservationId}: ${err.message}`);
      throw new Error(`Refund tx preparation failed: ${err.message}`);
    }
  },
};
